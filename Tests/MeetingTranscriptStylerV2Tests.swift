import Foundation

/// `format_version: 2` restyle: compact frontmatter, the hidden
/// `.meta/<capture_id>.json` sidecar, merged `[MM:SS] **Speaker:** text`
/// turns, and a second pass that changes nothing.
func testMeetingTranscriptStylerV2() {
    runSuite("MeetingTranscriptStylerV2Tests") {
        testV2FrontmatterKeepsHighSignalKeysAndMovesPlumbingToSidecar()
        testV2FrontmatterKeepsAbnormalHealthAndExplicitLanguage()
        testV2BodyMergesShortSameSpeakerTurnsIntoSingleLines()
        testV2RestyleIsIdempotent()
        testV2QualifiesLabelsWhenOneNameIsOnBothChannels()
        testV2RestylePreservesSummarySection()
        testV2SidecarFailureNeverFailsTheTranscriptSave()
        testTurnMergingLimits()
        testV2FrontmatterPassOverV2OutputMovesNothing()
        testV2PreservesHandEditedSummaryAndAiHeading()
        testV2SkipsMergingDuplicateSameChannelSpeakerRows()
        testV2PreservesRecordedAtOffsetAndKeepsKeysWithoutCaptureID()
        testV2DeletionIgnoresSymlinkedMetaDirectory()
    }
}

private let v2CaptureID = "5E9A0000-0000-0000-0000-0000000000C1"

private func v2RawTranscript(extraFrontmatter: String = "", health: String? = nil, speakers: String? = nil, transcript: String? = nil) -> String {
    let healthLines = health ?? """
    capture_quality: good
    audio_gaps: 2
    device_switches: 0
    system_audio_signal_verified: true
    gap_events:
      - "System audio reconnect: 0.4s"
      - "Sleep/wake: 12.0s"
    """
    let speakerLines = speakers ?? """
    speakers:
      - id: "1"
        channel: system
        db_id: "22222222-2222-2222-2222-222222222222"
        name: "Speaker 1"
        confidence: unknown
        source: db_pending
    """
    let transcriptLines = transcript ?? """
    [00:00] [Mic/You] Oh

    [00:02] [Mic/You] my god

    [00:05] [Mic/You] so that the top

    [00:07] [Mic/You] dry.

    [00:20] [System/Speaker 1] Right.

    [00:40] [Mic/You] Next point.
    """
    return """
    ---
    capture_id: "\(v2CaptureID)"
    capture_type: meeting
    title: "Roadmap sync"
    format_version: 1
    transcript_style: raw
    transcript_id: "\(v2CaptureID)"
    date: 2026-11-26
    time: 19:58:41
    duration: "8:34"
    processing_time: "41.3s"
    transcription_engine: parakeet_local
    diarization_engine: nemotron_offline
    sources: [mic, system_audio]
    mic_utterances: 5
    system_utterances: 1
    mic_speakers: 1
    system_speakers: 1
    total_word_count: 410
    voiceprint_model: "redimnet2-b4"
    starred: true
    transcription_language: "auto"
    transcription_language_resolution: automaticUncertain
    \(extraFrontmatter)\(healthLines)
    \(speakerLines)
    ---

    # Meeting Recording - Nov 26, 2026 at 7:58 PM

    **Duration:** 8:34 | **Words:** 410 | **Utterances:** 6

    ---

    ---

    ## Full Transcript

    \(transcriptLines)

    ---

    *Generated by Transcripted with Parakeet (local) | Duration: 8:34 | 410 words | 2 speakers*
    """
}

private func v2Restyle(_ raw: String, in directory: URL) -> (url: URL, markdown: String) {
    let url = directory.appendingPathComponent("Call_2026-11-26_19-58-41.md")
    try? raw.write(to: url, atomically: true, encoding: .utf8)
    let styled = MeetingTranscriptStyler.restyleTranscript(at: url)
    return (styled.url, (try? String(contentsOf: styled.url, encoding: .utf8)) ?? "")
}

private func v2TemporaryDirectory() -> URL {
    let directory = FileManager.default.temporaryDirectory
        .appendingPathComponent("MeetingTranscriptStylerV2Tests-\(UUID().uuidString)")
    try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    return directory
}

private func frontmatterLines(_ markdown: String) -> [String] {
    TranscriptFrontmatter.lines(in: markdown) ?? []
}

private func expectedRecordedAt() -> String {
    var components = DateComponents()
    components.year = 2026; components.month = 11; components.day = 26
    components.hour = 19; components.minute = 58; components.second = 41
    var calendar = Calendar(identifier: .gregorian)
    calendar.timeZone = .current
    let formatter = ISO8601DateFormatter()
    formatter.timeZone = .current
    formatter.formatOptions = [.withInternetDateTime]
    return formatter.string(from: calendar.date(from: components) ?? Date())
}

private func testV2FrontmatterKeepsHighSignalKeysAndMovesPlumbingToSidecar() {
    let directory = v2TemporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    let (url, markdown) = v2Restyle(v2RawTranscript(), in: directory)
    let lines = frontmatterLines(markdown)
    let values = TranscriptFrontmatter.values(in: markdown) ?? [:]

    assertEqual(Array(lines.prefix(10)), [
        "title: \"Roadmap sync\"",
        "capture_id: \"\(v2CaptureID)\"",
        "capture_type: meeting",
        "format_version: 2",
        "transcript_style: styled",
        "recorded_at: \(expectedRecordedAt())",
        "date: 2026-11-26",
        "time: 19:58:41",
        "duration: \"8:34\"",
        "total_word_count: 410",
    ], "high-signal keys come first, in a fixed order")
    assertEqual(values["starred"], "true")
    assertEqual(values["system_speakers"], "1", "multi-speaker calls keep the count speaker naming reads")
    assertEqual(values["audio_gaps"], "1", "sub-second reconnects don't count as gaps")
    assertTrue(markdown.contains("gap_events:\n  - \"Sleep/wake: 12.0s\"\n"), markdown)
    assertFalse(markdown.contains("System audio reconnect: 0.4s"), "sub-second reconnect noise is dropped")
    assertTrue(markdown.contains("speakers:\n  - id: \"1\"\n    channel: system"), "speakers block stays")
    for key in [
        "processing_time", "transcription_engine", "diarization_engine", "voiceprint_model",
        "mic_utterances", "system_utterances", "mic_speakers", "sources", "transcript_id",
        "capture_quality", "device_switches", "system_audio_signal_verified",
        "transcription_language", "transcription_language_resolution",
    ] {
        assertNil(values[key], "\(key) moves out of the Markdown")
    }

    let sidecarURL = directory.appendingPathComponent(".meta/\(v2CaptureID).json")
    let sidecar = MeetingMetadataSidecar.read(forTranscript: url, captureID: UUID(uuidString: v2CaptureID)!)
    assertEqual(sidecar?.captureID, v2CaptureID)
    assertEqual(sidecar?.frontmatter["transcription_engine"], .string("parakeet_local"))
    assertEqual(sidecar?.frontmatter["processing_time"], .string("41.3s"))
    assertEqual(sidecar?.frontmatter["capture_quality"], .string("good"))
    assertEqual(sidecar?.frontmatter["audio_gaps"], .string("2"))
    assertEqual(sidecar?.frontmatter["sources"], .list(["mic", "system_audio"]))
    assertEqual(
        sidecar?.frontmatter["gap_events"],
        .list(["System audio reconnect: 0.4s", "Sleep/wake: 12.0s"]),
        "the sidecar keeps every raw gap event"
    )
    let permissions = (try? FileManager.default.attributesOfItem(atPath: sidecarURL.path))?[.posixPermissions] as? NSNumber
    assertEqual(permissions, NSNumber(value: 0o600), "sidecar is owner-only")
    let sidecarText = (try? String(contentsOf: sidecarURL, encoding: .utf8)) ?? ""
    assertFalse(sidecarText.contains("Oh my god"), "the sidecar holds no transcript text")
}

private func testV2FrontmatterKeepsAbnormalHealthAndExplicitLanguage() {
    let directory = v2TemporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    let raw = v2RawTranscript(
        health: """
        capture_quality: degraded
        audio_gaps: 0
        device_switches: 3
        system_audio_signal_verified: false
        system_audio_missing: true
        mic_only: true
        audio_health: mic_attenuated_by_call_app
        mic_boost_prompt: "declined"
        """
    )
    .replacingOccurrences(of: "transcription_language: \"auto\"", with: "transcription_language: \"fi\"")
    .replacingOccurrences(of: "transcription_language_resolution: automaticUncertain", with: "transcription_language_resolution: explicit\ntranscription_language_resolved: \"fi\"")
    let (_, markdown) = v2Restyle(raw, in: directory)
    let values = TranscriptFrontmatter.values(in: markdown) ?? [:]

    assertEqual(values["capture_quality"], "degraded")
    assertEqual(values["device_switches"], "3")
    assertEqual(values["system_audio_signal_verified"], "false")
    assertEqual(values["system_audio_missing"], "true")
    assertEqual(values["mic_only"], "true")
    assertEqual(values["audio_health"], "mic_attenuated_by_call_app")
    assertEqual(values["mic_boost_prompt"], "declined")
    assertNil(values["audio_gaps"], "zero gaps is the default")
    assertEqual(values["transcription_language"], "fi")
    assertEqual(values["transcription_language_resolution"], "explicit")
    assertEqual(values["transcription_language_resolved"], "fi")
}

private func testV2BodyMergesShortSameSpeakerTurnsIntoSingleLines() {
    let directory = v2TemporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    let (_, markdown) = v2Restyle(v2RawTranscript(), in: directory)
    let body = TranscriptFrontmatter.body(in: markdown) ?? ""

    assertTrue(body.contains("""
    ## Transcript

    [00:00] **You:** Oh my god so that the top dry.

    [00:20] **Speaker 1:** Right.

    [00:40] **You:** Next point.
    """), body)
    assertFalse(body.contains("[Mic/"), "no per-line channel noise")
    assertFalse(body.contains("Generated by"), "the raw footer is gone")
    assertTrue(body.contains("  •  3 turns"), "the detail line counts merged turns")
}

private func testV2RestyleIsIdempotent() {
    let directory = v2TemporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    let (url, first) = v2Restyle(v2RawTranscript(), in: directory)
    let sidecarURL = directory.appendingPathComponent(".meta/\(v2CaptureID).json")
    let firstSidecar = try? Data(contentsOf: sidecarURL)

    let second = MeetingTranscriptStyler.restyleTranscript(at: url)
    let secondMarkdown = (try? String(contentsOf: second.url, encoding: .utf8)) ?? ""
    assertEqual(second.url, url, "a second pass keeps the file where it is")
    assertEqual(secondMarkdown, first, "a second restyle reads its own v2 output and changes nothing")
    assertEqual(try? Data(contentsOf: sidecarURL), firstSidecar, "nothing new to move keeps the sidecar")
}

private func testV2QualifiesLabelsWhenOneNameIsOnBothChannels() {
    let directory = v2TemporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    let raw = v2RawTranscript(
        speakers: """
        speakers:
          - id: "0"
            channel: mic
            name: "Dana"
            confidence: high
            source: db
          - id: "1"
            channel: system
            name: "Dana"
            confidence: unknown
            source: db_pending
        """,
        transcript: """
        [00:00] [Mic/Dana] Hi, it's me.

        [00:30] [System/Dana] Hi, it's also me.
        """
    )
    let (url, markdown) = v2Restyle(raw, in: directory)
    assertTrue(markdown.contains("[00:00] **Mic/Dana:** Hi, it's me."), markdown)
    assertTrue(markdown.contains("[00:30] **Dana:** Hi, it's also me."), markdown)

    let again = MeetingTranscriptStyler.restyleTranscript(at: url)
    assertEqual((try? String(contentsOf: again.url, encoding: .utf8)) ?? "", markdown, "qualified labels round-trip")
}

private func testV2RestylePreservesSummarySection() {
    let directory = v2TemporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    let (url, first) = v2Restyle(v2RawTranscript(), in: directory)
    let withSummary = first.replacingOccurrences(
        of: "\n## Transcript\n",
        with: "\n## Summary\n\nThe team picked the smaller launch.\n\n## Transcript\n"
    )
    try? withSummary.write(to: url, atomically: true, encoding: .utf8)

    let again = MeetingTranscriptStyler.restyleTranscript(at: url)
    let markdown = (try? String(contentsOf: again.url, encoding: .utf8)) ?? ""
    assertEqual(markdown, withSummary, "restyle keeps the summary section, once, before the transcript")
}

private func testV2SidecarFailureNeverFailsTheTranscriptSave() {
    let directory = v2TemporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    // A file where the `.meta` folder would go blocks the sidecar.
    try? "not a folder".write(to: directory.appendingPathComponent(".meta"), atomically: true, encoding: .utf8)
    let (url, markdown) = v2Restyle(v2RawTranscript(), in: directory)

    assertEqual(url.lastPathComponent, "2026-11-26 Roadmap sync.md")
    assertTrue(markdown.contains("format_version: 2"), "the transcript is still restyled")
    assertTrue(markdown.contains("transcription_engine: parakeet_local"), "pipeline keys stay in frontmatter when sidecar write fails")
    assertEqual(
        (try? String(contentsOf: directory.appendingPathComponent(".meta"), encoding: .utf8)) ?? "",
        "not a folder",
        "whatever was in the way is left alone"
    )
}

private func testTurnMergingLimits() {
    func turn(_ seconds: Int, _ name: String = "You", _ text: String = "word") -> MeetingTranscriptTurn {
        MeetingTranscriptTurn(
            timestamp: String(format: "%02d:%02d", seconds / 60, seconds % 60),
            channel: name == "You" ? .mic : .system,
            name: name,
            text: text
        )
    }
    func starts(_ turns: [MeetingTranscriptTurn]) -> [String] {
        MeetingTranscriptDialogue.merged(turns).map(\.timestamp)
    }

    assertEqual(starts([turn(0), turn(8), turn(16)]), ["00:00"], "pauses up to 8 s merge")
    assertEqual(starts([turn(0), turn(9)]), ["00:00", "00:09"], "a longer pause splits")
    assertEqual(starts([turn(0), turn(2, "Dana"), turn(4)]), ["00:00", "00:02", "00:04"], "a speaker switch splits")
    assertEqual(
        starts([turn(0), turn(6), turn(12), turn(18), turn(24), turn(30)]),
        ["00:00", "00:30"],
        "a merged turn spans at most 25 s"
    )
    let long = String(repeating: "a", count: 200)
    assertEqual(starts([turn(0, "You", long), turn(2, "You", long)]), ["00:00", "00:02"], "at most 320 characters")
    assertEqual(
        MeetingTranscriptDialogue.merged([turn(0, "You", "Oh"), turn(2, "You", "my god")]).first?.text,
        "Oh my god"
    )
    let merged = MeetingTranscriptDialogue.merged([turn(0), turn(8), turn(16), turn(30), turn(36)])
    assertEqual(MeetingTranscriptDialogue.merged(merged), merged, "merging merged turns changes nothing")

    let outOfOrder = [turn(0, "You", "a"), turn(7, "You", "b"), turn(5, "You", "c")]
    let once = MeetingTranscriptDialogue.merged(outOfOrder)
    assertEqual(MeetingTranscriptDialogue.merged(once), once, "out-of-order timestamps merge idempotently")
    assertEqual(once.map(\.text), ["a c b"], "stable-sorting before merge orders by start time")
}

private func testV2FrontmatterPassOverV2OutputMovesNothing() {
    let raw = TranscriptFrontmatter.lines(in: v2RawTranscript()) ?? []
    let date = Date(timeIntervalSince1970: 1_800_000_000)
    let first = MeetingTranscriptV2Frontmatter.render(lines: raw, titleLine: "title: \"Roadmap sync\"", recordedAt: date)
    assertEqual(first.movedValues["audio_gaps"], .string("2"))
    let second = MeetingTranscriptV2Frontmatter.render(
        lines: Array(first.lines.dropFirst()), titleLine: "title: \"Roadmap sync\"", recordedAt: date
    )
    assertEqual(second.lines, first.lines, "v2 frontmatter is a fixed point")
    assertTrue(second.movedValues.isEmpty, "nothing left to move, so the sidecar's raw values stay: \(second.movedValues)")
}

private func testV2PreservesHandEditedSummaryAndAiHeading() {
    let bodyWithUserSummary = """
    # Meeting at 7:58 PM

    Recorded Nov 26, 2026 at 7:58 PM  •  8m  •  1 turn

    ## Summary

    My own notes: we agreed to ship Friday.

    ## Transcript

    [00:00] **You:** Ship Friday.
    """
    let kept = MeetingTitlesBody.settingSummary(
        "Model generated summary.",
        replacing: "Earlier model summary.",
        in: bodyWithUserSummary
    )
    assertEqual(kept, bodyWithUserSummary, "hand-edited ## Summary stays untouched")

    let bodyWithModelSummary = bodyWithUserSummary.replacingOccurrences(
        of: "My own notes: we agreed to ship Friday.",
        with: "Earlier model summary."
    )
    let replaced = MeetingTitlesBody.settingSummary(
        "Updated model summary.",
        replacing: "Earlier model summary.",
        in: bodyWithModelSummary
    )
    assertTrue(replaced.contains("Updated model summary."), "matching previous model summary updates cleanly")
    assertFalse(replaced.contains("Earlier model summary."), "old model summary is removed")

    let directory = v2TemporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    let labeled = v2RawTranscript(
        extraFrontmatter: "ai_title: \"Billing switch\"\nai_title_replaces: \"Roadmap sync\"\n"
    )
    let (_, markdown) = v2Restyle(labeled, in: directory)
    assertTrue(markdown.contains("\n# Billing switch\n"), "restyle keeps active ai_title on the H1 heading")
}

private func testV2SkipsMergingDuplicateSameChannelSpeakerRows() {
