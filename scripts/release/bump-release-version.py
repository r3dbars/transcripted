#!/usr/bin/env python3
"""Bump Transcripted source version metadata without touching release surfaces."""

from __future__ import annotations

import argparse
import plistlib
import re
import shutil
import sys
import tempfile
from pathlib import Path


VERSION_PATTERN = re.compile(r"^\d+\.\d+\.\d+$")


def repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def validate_version(version: str) -> str:
    if not VERSION_PATTERN.fullmatch(version):
        raise ValueError(f"Version must look like x.y.z, got {version!r}")
    return version


def load_plist(path: Path) -> dict:
    with path.open("rb") as handle:
        return plistlib.load(handle)


def write_plist(path: Path, payload: dict) -> None:
    with path.open("wb") as handle:
        plistlib.dump(payload, handle, sort_keys=False)


def update_info_plist(path: Path, version: str, dry_run: bool) -> bool:
    if not path.exists():
        raise FileNotFoundError(f"Info.plist not found: {path}")

    payload = load_plist(path)
    changed = False
    for key in ("CFBundleShortVersionString", "CFBundleVersion"):
        if payload.get(key) != version:
            payload[key] = version
            changed = True

    if changed and not dry_run:
        write_plist(path, payload)
    return changed


MCP_VERSION_PATH = Path("Tools/TranscriptedMCP/Sources/TranscriptedMCP/BuildVersion.swift")


def mcp_version_source(version: str) -> str:
    validate_version(version)
    return (
        "// Generated by scripts/release/bump-release-version.py from Info.plist.\n"
        "// Do not edit: run the version bump script instead.\n"
        "enum MCPBuildVersion {\n"
        f'    static let value = "{version}"\n'
        "}\n"
    )


def check_mcp_version(repo: Path) -> bool:
    version = validate_version(load_plist(repo / "Info.plist")["CFBundleShortVersionString"])
    path = repo / MCP_VERSION_PATH
    return path.is_file() and path.read_text() == mcp_version_source(version)


def update_mcp_version(repo: Path, version: str, dry_run: bool) -> bool:
    path = repo / MCP_VERSION_PATH
    source = mcp_version_source(version)
    changed = not path.is_file() or path.read_text() != source
    if changed and not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source)
    return changed


def bump(repo: Path, version: str, dry_run: bool) -> list[str]:
    info_changed = update_info_plist(repo / "Info.plist", version, dry_run)
    mcp_changed = update_mcp_version(repo, version, dry_run)
    return [
        f"{MCP_VERSION_PATH}: {'would update' if dry_run and mcp_changed else 'updated' if mcp_changed else 'unchanged'}",
        f"Info.plist: {'would update' if dry_run and info_changed else 'updated' if info_changed else 'unchanged'}",
    ]


def self_test() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        fixture = root / "Info.plist"
        write_plist(
            fixture,
            {
                "CFBundleShortVersionString": "1.1.48",
                "CFBundleVersion": "1.1.48",
                "CFBundleName": "Transcripted",
            },
        )
        beta_dir = root / "Sources" / "Beta"
        beta_dir.mkdir(parents=True)
        beta_config = beta_dir / "BetaConfig.swift"
        beta_config.write_text('enum BetaConfig { static let appVersion = "1.1.48" }\n')

        messages = bump(root, "1.1.49", dry_run=False)
        payload = load_plist(fixture)
        assert payload["CFBundleShortVersionString"] == "1.1.49"
        assert payload["CFBundleVersion"] == "1.1.49"
        assert beta_config.read_text() == 'enum BetaConfig { static let appVersion = "1.1.48" }\n', "retired beta metadata must stay untouched"
        assert any("Info.plist: updated" == item for item in messages)
        mirror = root / MCP_VERSION_PATH
        assert mirror.read_text() == mcp_version_source("1.1.49")
        assert check_mcp_version(root)

        dry_root = root / "dry"
        shutil.copytree(root, dry_root)
        bump(dry_root, "1.1.50", dry_run=True)
        assert load_plist(dry_root / "Info.plist")["CFBundleShortVersionString"] == "1.1.49"
        assert (dry_root / MCP_VERSION_PATH).read_text() == mirror.read_text()
        mirror.write_text(mcp_version_source("1.1.48"))
        assert not check_mcp_version(root), "stale compiled version must fail"
        mirror.unlink()
        assert not check_mcp_version(root), "missing compiled version must fail"
        bump(root, "1.1.49", dry_run=False)
        assert check_mcp_version(root), "bump repairs the generated mirror"

    print("bump-release-version self-test passed")
    return 0


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=False, help="Target app version, for example 1.1.49.")
    parser.add_argument("--repo", default=str(repo_root()), help="Repo checkout to update. Defaults to this repo.")
    parser.add_argument("--dry-run", action="store_true", help="Print what would change without writing files.")
    parser.add_argument("--self-test", action="store_true", help="Run fixture tests and exit.")
    parser.add_argument("--check", action="store_true", help="Check the compiled MCP version matches Info.plist without writing.")
    args = parser.parse_args()
    if not args.self_test and not args.check and not args.version:
        parser.error("--version is required unless --self-test or --check is set")
    return args


def main() -> int:
    args = parse_args()
    if args.self_test:
        return self_test()

    try:
        repo = Path(args.repo).expanduser().resolve()
        if args.check:
            if not check_mcp_version(repo):
                raise ValueError("Compiled MCP version is missing or stale; run bump-release-version.py with the Info.plist version")
            print("Compiled MCP version matches Info.plist")
            return 0
        version = validate_version(args.version)
        for message in bump(repo, version, args.dry_run):
            print(message)
    except Exception as error:
        print(f"bump-release-version failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
