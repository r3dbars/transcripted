    mkdir -p "$COVERAGE_DIR"
    rm -f "$COVERAGE_DIR"/*.profraw "$COVERAGE_PROFDATA" "$COVERAGE_SUMMARY" "$COVERAGE_LCOV"
    TEST_BINARY="$COVERAGE_DIR/tests"
fi

echo "Compiling tests..."
