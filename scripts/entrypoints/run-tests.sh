    swiftc
)

if [ "$coverage_requested" = true ]; then
    SWIFTC_ARGS+=(
        -profile-generate
        -profile-coverage-mapping
    )
fi

SWIFTC_ARGS+=(
    "${FAST_TEST_SOURCES[@]}"
    "${APP_SOURCES[@]}"
    -framework AppKit
    -framework AVFoundation
    -framework ApplicationServices
    -framework Carbon
