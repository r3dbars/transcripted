#!/usr/bin/env python3
"""Rule registry: every repo check is listed, with what it enforces and why.

Checks pile up. After a while nobody can say which rule a script protects, what
past mistake it came from, or whether a rule in AGENTS.md has anything behind it
at all. `.agents/rules.json` pairs each rule with the thing that enforces it
(architecture, a type, a lint, a test, a hook, or only a doc), and
`docs/rules.md` is that table, generated so it can't drift. lint.py rules
(`scripts/dev/lint_rules/`) aren't repeated in rules.json; they're merged in from
their modules.

This check fails when:
  - a `scripts/dev/check-*.py` or `scripts/dev/concurrency-census.*` script is
    neither the enforcer of a registry entry nor listed in `unregistered_ok`
    (with a reason), or an `unregistered_ok` entry is stale (gone, or now
    registered);
  - an entry is missing a field, has an unknown level, or reuses an id (across
    the registry and lint.py rules);
  - a script path an enforcer names, or an owner_doc, doesn't exist;
  - `docs/rules.md` isn't exactly what `--write` would generate.

    python3 scripts/dev/check-rule-registry.py            # check
    python3 scripts/dev/check-rule-registry.py --write    # regenerate docs/rules.md
    python3 scripts/dev/check-rule-registry.py --self-test

Offline, python3 stdlib only, writes nothing except docs/rules.md on --write.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import shlex
import sys
import tempfile
from pathlib import Path

DEV_DIR = Path(__file__).resolve().parent
REPO_ROOT = DEV_DIR.parents[1]
REGISTRY_REL = ".agents/rules.json"
DOC_REL = "docs/rules.md"
LEVELS = ("architecture", "type", "lint", "test", "hook", "doc")
REQUIRED = ("id", "enforces", "enforcer", "level", "owner_doc", "why", "runs_in", "proof")
CHECK_GLOBS = ("scripts/dev/check-*.py", "scripts/dev/concurrency-census.*")
SCRIPT_SUFFIXES = (".py", ".sh", ".rb", ".swift", ".json", ".yml", ".yaml", ".md")
GENERATED_LINE = ("<!-- Generated by `python3 scripts/dev/check-rule-registry.py --write` from "
                  ".agents/rules.json and scripts/dev/lint_rules/. Don't edit by hand. -->")
LINT_ENFORCER = "python3 scripts/dev/lint.py"
LINT_RUNS_IN = ["Claude edit hook (--hook)", "Stop hook (--changed)", "pre-push (--range)", "linux-checks + repo-hygiene CI (--all)"]


# ---------------------------------------------------------------- loading

def load_lint_entries(dev_dir: Path = DEV_DIR):
    """lint.py rules (plus the built-in lint-allow-format) as registry-shaped
    entries. Returns (entries, load_errors)."""
    spec = importlib.util.spec_from_file_location("lint_runner", dev_dir / "lint.py")
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    rules, errors = module.load_rules()
    entries = []
    for rule in [module.ALLOW_RULE] + rules:
        m = rule.meta
        entries.append({
            "id": m["id"],
            "enforces": m["summary"],
            "enforcer": f"{LINT_ENFORCER} (`--explain {m['id']}`)",
            "level": "lint",
            "owner_doc": m["owner_doc"],
            "why": m["why"],
            "runs_in": LINT_RUNS_IN,
            "proof": ", ".join(m.get("proof", [])),
            "source": rule.source,
        })
    return entries, errors


def load_registry(root: Path) -> dict:
    return json.loads((root / REGISTRY_REL).read_text(encoding="utf-8"))


# ---------------------------------------------------------------- validation

def enforcer_paths(enforcer: str) -> list:
    """Script/file paths an enforcer command names (relative to the repo root)."""
    try:
        tokens = shlex.split(enforcer)
    except ValueError:
        tokens = enforcer.split()
    out = []
    for tok in tokens:
        tok = tok.strip("`(),;")
        if not tok or tok.startswith("-") or any(c in tok for c in "*?$<>{}"):
            continue
        if tok.endswith(SCRIPT_SUFFIXES) and ("/" in tok or tok.endswith((".sh", ".py"))):
            out.append(tok)
    return out


def check_scripts(root: Path) -> list:
    found = set()
    for pattern in CHECK_GLOBS:
        found.update(p.relative_to(root).as_posix() for p in root.glob(pattern) if p.is_file())
    return sorted(found)


def validate(root: Path, registry, lint_entries, lint_errors=()) -> list:
    errors = [f"lint.py rule error: {e}" for e in lint_errors]
    if not isinstance(registry, dict):
        return errors + [f"{REGISTRY_REL}: top level must be an object with 'rules' and 'unregistered_ok'"]
    for key in registry:
        if key not in ("rules", "unregistered_ok") and not key.startswith("_"):
            errors.append(f"{REGISTRY_REL}: unknown top-level key {key!r}")
    entries = registry.get("rules", [])
    unregistered = registry.get("unregistered_ok", {})
    if not isinstance(entries, list):
        return errors + [f"{REGISTRY_REL}: 'rules' must be a list"]
    if not isinstance(unregistered, dict):
        return errors + [f"{REGISTRY_REL}: 'unregistered_ok' must be an object of path -> reason"]

    seen: dict = {}
    registered_paths = set()
    for idx, entry in enumerate(entries):
        label = f"{REGISTRY_REL} rules[{idx}]"
        if not isinstance(entry, dict):
            errors.append(f"{label}: must be an object")
            continue
        label = f"{REGISTRY_REL} rule {entry.get('id', '?')!r}"
        missing = [k for k in REQUIRED if k not in entry]
        if missing:
            errors.append(f"{label}: missing {', '.join(missing)}")
            continue
        for key in ("id", "enforces", "enforcer", "owner_doc", "why", "proof"):
            if not isinstance(entry[key], str) or not entry[key].strip():
                errors.append(f"{label}: {key} must be a non-empty string")
        if entry["level"] not in LEVELS:
            errors.append(f"{label}: level {entry['level']!r} must be one of {', '.join(LEVELS)}")
        if not isinstance(entry["runs_in"], list) or not all(isinstance(x, str) and x for x in entry["runs_in"]):
            errors.append(f"{label}: runs_in must be a list of strings")
        if isinstance(entry["owner_doc"], str) and entry["owner_doc"] and not (root / entry["owner_doc"]).is_file():
            errors.append(f"{label}: owner_doc {entry['owner_doc']} does not exist")
        if isinstance(entry["enforcer"], str):
            paths = enforcer_paths(entry["enforcer"])
            for p in paths:
                if not (root / p).exists():
                    errors.append(f"{label}: enforcer names {p}, which does not exist")
                registered_paths.add(p)
        rid = entry.get("id")
        if isinstance(rid, str):
            if rid in seen:
                errors.append(f"{label}: id already used by {seen[rid]}")
            seen[rid] = REGISTRY_REL
    for entry in lint_entries:
        rid = entry["id"]
        if rid in seen:
            errors.append(f"lint.py rule {rid!r}: id already used in {seen[rid]}")
        seen[rid] = entry.get("source") or "lint.py"
        if not (root / entry["owner_doc"]).is_file():
            errors.append(f"lint.py rule {rid!r}: owner_doc {entry['owner_doc']} does not exist")

    for path in check_scripts(root):
        if path not in registered_paths and path not in unregistered:
            errors.append(f"{path} is a check but no {REGISTRY_REL} entry names it as its enforcer. Add an entry "
                          f"(id, enforces, enforcer, level, owner_doc, why, runs_in, proof), or list it under "
                          f"unregistered_ok with a reason")
    for path, reason in sorted(unregistered.items()):
        if not isinstance(reason, str) or not reason.strip():
            errors.append(f"{REGISTRY_REL} unregistered_ok {path}: needs a reason")
        if not (root / path).exists():
            errors.append(f"{REGISTRY_REL} unregistered_ok {path}: file is gone; remove the entry")
        elif path in registered_paths:
            errors.append(f"{REGISTRY_REL} unregistered_ok {path}: now registered as an enforcer; remove it from unregistered_ok")

    if not errors:
        expected = render(registry, lint_entries)
        doc = root / DOC_REL
        actual = doc.read_text(encoding="utf-8") if doc.is_file() else None
        if actual != expected:
            state = "is missing" if actual is None else "is out of date"
            errors.append(f"{DOC_REL} {state}; run python3 scripts/dev/check-rule-registry.py --write")
    return errors


# ---------------------------------------------------------------- rendering

def _cell(value) -> str:
    if isinstance(value, list):
        value = "; ".join(value)
    return str(value).replace("\n", " ").replace("|", "\\|").strip()


def render(registry: dict, lint_entries) -> str:
    rows = [dict(e) for e in registry.get("rules", [])] + [dict(e) for e in lint_entries]
    rows.sort(key=lambda e: (LEVELS.index(e["level"]) if e.get("level") in LEVELS else len(LEVELS), e["id"]))
    out = [
        GENERATED_LINE,
        "",
        "# Rules and what enforces them",
        "",
        "Each row is a rule the code has to keep true and the thing that fails when it doesn't. "
        "When a mistake keeps coming back, fix it at the highest level that works: architecture "
        "(one way to do it), then types, then a lint whose error names the fix, then a test, and docs "
        "only for judgment calls. Lint rules live in `scripts/dev/lint_rules/` and run through "
        "`scripts/dev/lint.py`; `python3 scripts/dev/lint.py --explain <id>` prints one in full. "
        "Everything else is registered in `.agents/rules.json`.",
        "",
        "| Rule | Level | Enforces | Enforcer | Runs in | Owner doc | Proof |",
        "|---|---|---|---|---|---|---|",
    ]
    for e in rows:
        out.append("| " + " | ".join([
            f"`{_cell(e['id'])}`", _cell(e["level"]), _cell(e["enforces"]), _cell(e["enforcer"]),
            _cell(e["runs_in"]), f"`{_cell(e['owner_doc'])}`", _cell(e["proof"]),
        ]) + " |")
    unregistered = registry.get("unregistered_ok", {})
    if unregistered:
        out += ["", "## Checks not registered yet", "",
                "These checks exist but don't have a registry entry yet. Each needs one: what it enforces, "
                "its level, owner doc, why it exists and its proof.", ""]
        for path, reason in sorted(unregistered.items()):
            out.append(f"- `{path}`: {_cell(reason)}")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- self-test

def self_test() -> int:
    failures = []

    def expect(cond, label):
        if not cond:
            failures.append(label)

    lint_entry = {"id": "no-bang", "enforces": "no force unwrap", "enforcer": f"{LINT_ENFORCER} (`--explain no-bang`)",
                  "level": "lint", "owner_doc": "AGENTS.md", "why": "w", "runs_in": LINT_RUNS_IN,
                  "proof": "abc1234:Sources/A.swift", "source": "scripts/dev/lint_rules/no_bang.py"}

    def entry(**kw):
        base = {"id": "file-size", "enforces": "no new Swift file over 800 lines",
                "enforcer": "python3 scripts/dev/check-a.py", "level": "lint", "owner_doc": "AGENTS.md",
                "why": "big files lose the thread", "runs_in": ["linux-checks"], "proof": "self-test"}
        base.update(kw)
        return base

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        (root / "scripts/dev").mkdir(parents=True)
        (root / ".agents").mkdir()
        (root / "docs").mkdir()
        (root / "AGENTS.md").write_text("x\n")
        for name in ("check-a.py", "check-b.py", "concurrency-census.sh", "other.py"):
            (root / "scripts/dev" / name).write_text("")

        def run(reg, lint=(lint_entry,), write=True):
            if write:
                (root / DOC_REL).write_text(render(reg, list(lint)))
            return validate(root, reg, list(lint))

        good = {"rules": [entry()], "unregistered_ok": {"scripts/dev/check-b.py": "pending backfill",
                                                         "scripts/dev/concurrency-census.sh": "pending backfill"}}
        expect(run(good) == [], f"valid registry passes: {run(good)}")
        doc = (root / DOC_REL).read_text()
        expect(doc.startswith(GENERATED_LINE + "\n"), "doc starts with the generated line")
        expect(doc.index("`file-size`") < doc.index("`no-bang`"), "rows sorted by level then id")
        expect("- `scripts/dev/check-b.py`: pending backfill" in doc, "unregistered checks listed")
        arch = dict(good, rules=[entry(), entry(id="aaa-arch", level="architecture", enforcer="python3 scripts/dev/check-b.py")],
                    unregistered_ok={"scripts/dev/concurrency-census.sh": "pending"})
        expect(run(arch) == [], f"architecture entry ok: {run(arch)}")
        doc = (root / DOC_REL).read_text()
        expect(doc.index("`aaa-arch`") < doc.index("`file-size`"), "architecture sorts before lint")

        errs = run(dict(good, unregistered_ok={"scripts/dev/check-b.py": "x"}))
        expect(any("concurrency-census.sh is a check" in e for e in errs), "unregistered census script fails")
        errs = run(dict(good, rules=[entry(enforcer="python3 scripts/dev/check-gone.py")]))
        expect(any("check-gone.py, which does not exist" in e for e in errs), "missing enforcer path fails")
        expect(any("check-a.py is a check" in e for e in errs), "check-a now unregistered fails")
        errs = run(dict(good, rules=[entry(owner_doc="docs/nope.md")]))
        expect(any("owner_doc docs/nope.md" in e for e in errs), "missing owner_doc fails")
        errs = run(dict(good, rules=[entry(), entry(enforcer="bash scripts/dev/concurrency-census.sh")]))
        expect(any("id already used" in e for e in errs), "duplicate registry id fails")
        errs = run(dict(good, rules=[entry(id="no-bang")]))
        expect(any("'no-bang': id already used" in e for e in errs), "registry id clashing with a lint rule fails")
        errs = run(dict(good, rules=[entry(level="vibes")]))
        expect(any("level 'vibes'" in e for e in errs), "unknown level fails")
        errs = run(dict(good, rules=[{k: v for k, v in entry().items() if k != "why"}]))
        expect(any("missing why" in e for e in errs), "missing field fails")
        errs = run(dict(good, unregistered_ok=dict(good["unregistered_ok"], **{"scripts/dev/check-a.py": "x"})))
        expect(any("check-a.py: now registered" in e for e in errs), "stale unregistered_ok (registered) fails")
        errs = run(dict(good, unregistered_ok=dict(good["unregistered_ok"], **{"scripts/dev/check-zz.py": "x"})))
        expect(any("check-zz.py: file is gone" in e for e in errs), "stale unregistered_ok (gone) fails")
        errs = run(dict(good, unregistered_ok=dict(good["unregistered_ok"], **{"scripts/dev/check-b.py": ""})))
        expect(any("needs a reason" in e for e in errs), "empty reason fails")
        errs = run(dict(good, extra=1))
        expect(any("unknown top-level key" in e for e in errs), "unknown top-level key fails")
        run(good)
        (root / DOC_REL).write_text((root / DOC_REL).read_text() + "hand edit\n")
        errs = validate(root, good, [lint_entry])
        expect(any("out of date" in e for e in errs), "hand-edited doc fails")
        (root / DOC_REL).unlink()
        errs = validate(root, good, [lint_entry])
        expect(any("is missing" in e for e in errs), "missing doc fails")
        errs = validate(root, good, [lint_entry], ["bad_rule: RULE is missing 'why'"])
        expect(any("lint.py rule error" in e for e in errs), "lint.py load errors surface")

    expect(enforcer_paths("python3 scripts/dev/check-a.py --self-test") == ["scripts/dev/check-a.py"], "enforcer path parse")
    expect(enforcer_paths("bash run-tests.sh --filter Foo") == ["run-tests.sh"], "root script parse")
    expect(enforcer_paths("python3 scripts/dev/lint.py (`--explain x`)") == ["scripts/dev/lint.py"], "lint enforcer parse")
    expect(_cell("a|b\nc") == "a\\|b c", "cells escape pipes and newlines")

    if failures:
        print("check-rule-registry self-test FAILED:")
        for f in failures:
            print(f"  - {f}")
        return 1
    print("check-rule-registry self-test passed")
    return 0


# ---------------------------------------------------------------- main

def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--write", action="store_true", help=f"regenerate {DOC_REL}")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args(argv)
    if args.self_test:
        return self_test()
    try:
        registry = load_registry(REPO_ROOT)
    except (OSError, json.JSONDecodeError) as error:
        print(f"check-rule-registry: can't read {REGISTRY_REL}: {error}")
        return 1
    lint_entries, lint_errors = load_lint_entries()
    if args.write:
        (REPO_ROOT / DOC_REL).write_text(render(registry, lint_entries), encoding="utf-8")
        print(f"check-rule-registry: wrote {DOC_REL} ({len(registry.get('rules', [])) + len(lint_entries)} rules)")
    errors = validate(REPO_ROOT, registry, lint_entries, lint_errors)
    if errors:
        print(f"check-rule-registry: {len(errors)} problem(s):")
        for e in errors:
            print(f"  - {e}")
        return 1
    print(f"check-rule-registry: ok ({len(registry.get('rules', []))} registered, {len(lint_entries)} lint.py, "
          f"{len(registry.get('unregistered_ok', {}))} not registered yet)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
