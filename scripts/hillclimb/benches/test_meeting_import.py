class IsolationTests(Harness):
    def test_fresh_empty_speaker_db_every_run_and_env(self):
        with mock.patch.dict(os.environ, {"TRANSCRIPTED_SPEAKER_EMBEDDER": "eres2net"}):
            self.run_bench([self.item("a"), self.item("b")])
        calls = self.calls()
        self.assertEqual(len(calls), 3)
        paths = [call["speaker_db"]["path"] for call in calls]
        self.assertEqual(len(set(paths)), 3)
        for call in calls:
            db = call["speaker_db"]
            self.assertTrue(db["exists"])
            self.assertGreater(db["size"], 0)
            self.assertEqual(db["tables"], 0)
            self.assertEqual(db["quick_check"], "ok")
            self.assertEqual(call["env"]["TRANSCRIPTED_DISABLE_FILE_LOGGER"], "1")
            self.assertEqual(call["env"]["TRANSCRIPTED_SPEAKER_EMBEDDER"], "eres2net")
            self.assertTrue(Path(call["env"]["TMPDIR"]).is_absolute())
            argv = call["argv"]
            for flag in ("--no-retain-audio", "--no-download", "--json", "--output-dir"):
                self.assertIn(flag, argv)
            self.assertNotIn("--speaker-embedder", argv)
        self.assertFalse(any(Path(path).exists() for path in paths))

    def test_warmup_runs_shortest_item_untimed(self):
        long_item = self.item("long", seconds=4.0, duration_s=4.0)
        short_item = self.item("short", seconds=2.0, duration_s=2.0)
        result = self.run_bench([long_item, short_item])
        calls = self.calls()
        self.assertEqual([call["audio"] for call in calls], ["short.wav", "long.wav", "short.wav"])
        for row in result["items"]:
            self.assertLess(row["metrics"]["turnaround_s"], 0.5)  # the 0.6 s first load was not counted
        warmup = result["environment"]["warmup"]
        self.assertEqual((warmup["enabled"], warmup["ran"], warmup["item"], warmup["ok"], warmup["counted"]),
                         (True, True, "short", True, False))
        self.assertGreaterEqual(warmup["seconds"], 0.6)

    def test_without_warmup_first_item_pays_model_load(self):
        result = self.run_bench([self.item("first"), self.item("second")], warmup=False)
        self.assertEqual(len(self.calls()), 2)
        self.assertGreaterEqual(self.row(result, "first")["metrics"]["turnaround_s"], 0.6)
        self.assertEqual(result["environment"]["warmup"], {"enabled": False})

