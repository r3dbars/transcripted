def write_wav(path: Path, seconds: float, rate: int = 16_000) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(rate)
        handle.writeframes(b"\x00\x00" * int(seconds * rate))
    return path


class Harness(unittest.TestCase):
    """Temp dir with a fake CLI, audio items, and a request writer."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)
        self.bin_dir = self.root / "bin"
        self.bin_dir.mkdir()
        self.cli = self.bin_dir / "transcripted-cli"
        grandchild = textwrap.indent(grandchild_snippet('control["grandchild_pid_file"]'), " " * 8).strip()
        self.cli.write_text(FAKE_CLI.replace("__PYTHON__", sys.executable).replace("__GRANDCHILD__", grandchild))
        self.cli.chmod(0o755)
        self.audio_dir = self.root / "audio"
        self.work = self.root / "work"
        self.work.mkdir()

    def tearDown(self):
        self._tmp.cleanup()

    def item(self, item_id: str, *, seconds: float = 2.0, control: dict | None = None, **fields) -> dict:
        audio = write_wav(self.audio_dir / f"{item_id}.wav", seconds)
        if control is not None:
            (self.audio_dir / f"{item_id}.wav.fake.json").write_text(json.dumps(control))
        return {"id": item_id, "audio": str(audio), **fields}

    def truth(self, name: str, text: str) -> str:
        path = self.audio_dir / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        return str(path)

    def request(self, items: list[dict], *, knobs: dict | None = None, **options) -> dict:
        bench_options = {"cli_binary": str(self.cli), **options}
        return {
            "schema": "transcripted.hillclimb.request.v1",
            "trial_id": "t0001",
            "objective": "meeting-turnaround",
            "suite": "meeting-corpus",
            "split": "dev",
            "repetition": 0,
            "knobs": knobs or {},
            "items": items,
            "bench_options": bench_options,
            "result_path": str(self.work / "result.json"),
        }

    def run_bench(self, items: list[dict], **kwargs) -> dict:
        result = meeting_import.run_request(self.request(items, **kwargs))
        self.assertEqual(validate_result(result, [item["id"] for item in items]), [])
        self.assertEqual([row["id"] for row in result["items"]], [item["id"] for item in items])
        return result

    def calls(self) -> list[dict]:
        log = self.bin_dir / "calls.jsonl"
        return [json.loads(line) for line in log.read_text().splitlines()] if log.exists() else []

    def row(self, result: dict, item_id: str) -> dict:
        return next(row for row in result["items"] if row["id"] == item_id)


class MetricsTests(Harness):
    def test_turnaround_rtf_and_frontmatter_metrics(self):
        result = self.run_bench([self.item("m1", control={"sleep": 0.05}, duration_s=10.0)])
        row = self.row(result, "m1")
        metrics = row["metrics"]
        self.assertIsNone(row["error"])
        self.assertEqual(row["gates"], {"no_transcript": 0, "empty_transcript": 0})
        self.assertGreaterEqual(metrics["turnaround_s"], 0.05)
        self.assertAlmostEqual(metrics["turnaround_rtf"], metrics["turnaround_s"] / 10.0)
        self.assertEqual(metrics["audio_duration_s"], 10.0)
        self.assertEqual(metrics["pipeline_processing_s"], 1.5)
        self.assertEqual(metrics["transcript_words"], 4.0)
        self.assertEqual(metrics["speaker_count"], 2.0)
        self.assertNotIn("word_recall", metrics)  # no truth, no metric
        self.assertNotIn("speaker_count_error", metrics)

    def test_duration_falls_back_to_frontmatter_then_wave(self):
        result = self.run_bench([
            self.item("front", control={"duration": "1:02"}),
            self.item("wav", seconds=3.0, control={"duration": None}),
        ])
        self.assertEqual(self.row(result, "front")["metrics"]["audio_duration_s"], 62.0)
        self.assertAlmostEqual(self.row(result, "wav")["metrics"]["audio_duration_s"], 3.0)
        self.assertEqual(meeting_import.parse_clock("1:02:03"), 3723.0)
        self.assertEqual(meeting_import.parse_seconds("12.3s"), 12.3)

    def test_word_recall_reuses_compare_meeting_corpus(self):
        compare = meeting_import.compare_module()
        truth = self.truth("plain.txt", "Hello there, general Kenobi. You are a bold one")
        zoom = self.truth("zoom.txt", "[Alice] 00:00:01 hello there\n[Bob] 00:00:04\ngeneral kenobi\n")
        result = self.run_bench([self.item("plain", truth=truth), self.item("zoom", truth=zoom)])
        expected = compare.overlap_metrics(compare.tokenize(Path(truth).read_text()),
                                           ["hello", "there", "general", "kenobi"])["recall"]
        self.assertAlmostEqual(self.row(result, "plain")["metrics"]["word_recall"], expected)
        self.assertAlmostEqual(expected, 4 / 9)
        self.assertEqual(self.row(result, "zoom")["metrics"]["word_recall"], 1.0)

    def test_speaker_count_error(self):
        rows = [["Speaker 0", "a b"], ["Speaker 1", "c d"], ["Speaker 2", "e f"], ["Speaker 0", "g"]]
        result = self.run_bench([
            self.item("three", control={"rows": rows}, speakers=5),
            self.item("exact", speakers=2),
        ])
        self.assertEqual(self.row(result, "three")["metrics"]["speaker_count"], 3.0)
        self.assertEqual(self.row(result, "three")["metrics"]["speaker_count_error"], 2.0)
        self.assertEqual(self.row(result, "exact")["metrics"]["speaker_count_error"], 0.0)


