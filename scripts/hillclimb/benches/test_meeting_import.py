def db_info(path):
    info = {"path": path, "exists": os.path.isfile(path), "size": 0, "tables": None, "quick_check": None}
    if info["exists"]:
        info["size"] = os.path.getsize(path)
        con = sqlite3.connect(path)
        info["tables"] = con.execute("select count(*) from sqlite_schema").fetchone()[0]
        info["quick_check"] = con.execute("PRAGMA quick_check").fetchone()[0]
