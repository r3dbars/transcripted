    def test_folder_ids_are_content_hashes_and_stable(self):
        folder = self.root / "calls"
        write_wav(folder / "one.wav", 2.0)
        write_wav(folder / "sub" / "two.wav", 2.5)
        (folder / "one.txt").write_text("[Alice] 00:00:01 hi\n[Bob] 00:00:02 yo\n")
        items, _ = make_meeting_suite.items_from_folder(folder)
        moved = self.root / "elsewhere"
        shutil.copytree(folder, moved)
        moved_items, _ = make_meeting_suite.items_from_folder(moved)
        self.assertEqual(sorted(i["id"] for i in items), sorted(i["id"] for i in moved_items))
        by_name = {Path(item["audio"]).name: item for item in items}
        digest = hashlib.sha256((folder / "one.wav").read_bytes()).hexdigest()[:12]
        self.assertEqual(by_name["one.wav"]["id"], "clip-" + digest)
        self.assertEqual(by_name["one.wav"]["speakers"], 2)
        self.assertNotIn("truth", by_name["two.wav"])
        self.assertAlmostEqual(by_name["two.wav"]["duration_s"], 2.5)
        for item in items:
            self.assertNotIn("calls", item["id"])

